//! Consistency rules. Each rule has a stable id; `error` means the profile contradicts itself.

use std::collections::BTreeSet;

use serde::{Deserialize, Serialize};
use serde_json::{json, Value};

use crate::data::{dataset, Dataset, VersionDef};
use crate::generate::{
    app_version, brand_list, languages_for, masked_webgl, oscpu, platform, vendor, UaContext,
};
use crate::model::{Engine, Kind, Profile};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Severity {
    Error,
    Warning,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Issue {
    pub rule: String,
    pub severity: Severity,
    pub message: String,
    /// What to do about it, in plain English.
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub hint: String,
    /// Machine-readable repair: which profile field and what it should be.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub fix: Option<Fix>,
}

/// Machine-readable repair for one issue.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Fix {
    /// JSON pointer into the profile (or into the collector output for `live.*` rules).
    pub path: String,
    pub action: FixAction,
    /// The value `path` should have, when the validator can compute it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub expected: Option<serde_json::Value>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum FixAction {
    /// Replace the value at `path` with `expected`.
    Set,
    /// Merge the `expected` object into the object at `path`.
    Merge,
    /// Delete `path`.
    Remove,
    /// No single value fixes it; regenerate or review the profile.
    Review,
}

#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Report {
    /// `true` when there is no `error`-level issue.
    pub valid: bool,
    /// 100 for a clean profile; each error costs 25 points, each warning 5.
    pub score: u32,
    pub issues: Vec<Issue>,
    /// Version of the rule set that produced this report (see `RULES_VERSION`).
    #[serde(default)]
    pub rules_version: String,
}

#[derive(Default)]
pub(crate) struct Collector(Vec<Issue>);

impl Collector {
    pub fn push(&mut self, severity: Severity, rule: &str, message: String) {
        self.0.push(Issue {
            rule: rule.to_owned(),
            severity,
            message,
            hint: String::new(),
            fix: None,
        });
    }
    /// Like `push`, with the value the field should have (`null` means "remove it").
    pub fn push_fix(
        &mut self,
        severity: Severity,
        rule: &str,
        message: String,
        expected: serde_json::Value,
    ) {
        self.push(severity, rule, message);
        if let Some(last) = self.0.last_mut() {
            last.fix = Some(Fix {
                path: String::new(),
                action: FixAction::Set,
                expected: Some(expected),
            });
        }
    }
    pub fn fix_if(
        &mut self,
        severity: Severity,
        failed: bool,
        rule: &str,
        expected: impl FnOnce() -> serde_json::Value,
        message: impl FnOnce() -> String,
    ) {
        if failed {
            self.push_fix(severity, rule, message(), expected());
        }
    }
    /// Add a fully formed issue (custom rules bring their own hint and fix).
    pub fn push_issue(&mut self, issue: Issue) {
        self.0.push(issue);
    }
    /// Drop issues whose rule the caller disabled.
    pub fn retain(&mut self, keep: impl Fn(&Issue) -> bool) {
        self.0.retain(keep);
    }
    pub fn error_if(&mut self, failed: bool, rule: &str, message: impl FnOnce() -> String) {
        if failed {
            self.push(Severity::Error, rule, message());
        }
    }
    pub fn warn_if(&mut self, failed: bool, rule: &str, message: impl FnOnce() -> String) {
        if failed {
            self.push(Severity::Warning, rule, message());
        }
    }
    pub fn finish(mut self) -> Report {
        for issue in &mut self.0 {
            crate::validator::annotate(issue);
        }
        let penalty: u32 = self
            .0
            .iter()
            .map(|i| match i.severity {
                Severity::Error => 25,
                Severity::Warning => 5,
            })
            .sum();
        Report {
            valid: self.0.iter().all(|i| i.severity != Severity::Error),
            score: 100u32.saturating_sub(penalty),
            issues: self.0,
            rules_version: crate::validator::RULES_VERSION.to_owned(),
        }
    }
}

/// Check a profile, generated by Veneer or brought from elsewhere, against every rule.
pub fn validate(p: &Profile) -> Report {
    let mut c = Collector::default();
    check_into(p, &mut c);
    c.finish()
}

/// Every built-in rule that needs nothing but the profile.
pub(crate) fn check_into(p: &Profile, c: &mut Collector) {
    match dataset() {
        Ok(data) => check(data, p, c),
        Err(e) => c.push(Severity::Error, "dataset.load", e.to_string()),
    }
}

fn check(data: &Dataset, p: &Profile, c: &mut Collector) {
    let nav = &p.navigator;
    let engine = p.browser.engine;
    let kind = p.device.kind;

    generic_rules(p, c);
    crate::extras::validate(data, p, c);
    // Touch support is a device fact (Vision Pro, touchscreen handhelds), so known devices are checked exactly.
    match data.device(&p.device.id) {
        Some(d) => c.fix_if(
            Severity::Error,
            nav.max_touch_points != d.touch_points,
            "device.touch_points",
            || json!(d.touch_points),
            || format!("`{}` reports {} touch points", d.id, d.touch_points),
        ),
        None => c.warn_if(
            !kind.is_handheld() && nav.max_touch_points > 0,
            "navigator.touch_desktop",
            || "touch on a non-handheld device is rare".into(),
        ),
    }

    let (Some(os), Some(browser)) = (data.os.get(&p.os.id), data.browsers.get(&p.browser.id))
    else {
        c.push(
            Severity::Warning,
            "profile.known",
            format!(
                "os `{}` or browser `{}` is not in the dataset; dataset rules skipped",
                p.os.id, p.browser.id
            ),
        );
        return;
    };
    c.error_if(browser.engine != engine, "browser.engine", || {
        format!("`{}` uses engine {:?}", p.browser.id, browser.engine)
    });
    let Some(template) = browser.ua.get(&p.os.id) else {
        c.push(
            Severity::Error,
            "browser.available_on_os",
            format!("`{}` does not ship on `{}`", p.browser.id, p.os.id),
        );
        return;
    };

    let os_version = os.version(&p.os.version);
    c.warn_if(os_version.is_none(), "os.known_version", || {
        format!("`{}` {} is not in the dataset", p.os.id, p.os.version)
    });
    let device = data.device(&p.device.id);
    c.warn_if(device.is_none(), "device.known", || {
        format!("device `{}` is not in the dataset", p.device.id)
    });
    if let Some(d) = device {
        c.error_if(d.os != p.os.id, "device.os", || {
            format!("`{}` runs `{}`", d.id, d.os)
        });
        c.error_if(d.kind != kind, "device.kind", || {
            format!("`{}` is a {:?}", d.id, d.kind)
        });
        if let Some(v) = os_version {
            c.error_if(!d.runs(v), "device.os_version", || {
                format!("`{}` cannot run {} {}", d.id, os.name, v.name)
            });
        }
        c.warn_if(
            !d.browsers.contains_key(&p.browser.id),
            "device.browser",
            || format!("`{}` is not a known browser on `{}`", p.browser.id, d.id),
        );
    }

    let pin = os_version.and_then(|v| v.pins.get(&p.browser.id));
    if let Some(v) = os_version {
        c.error_if(
            !v.supports(&p.browser.id),
            "browser.os_version_support",
            || format!("`{}` does not run on {} {}", p.browser.id, os.name, v.name),
        );
    }
    if let Some(pin) = pin {
        c.fix_if(
            Severity::Error,
            *pin != p.browser.version,
            "browser.os_version_pin",
            || json!(pin),
            || format!("{} {} ships {} {pin}", os.name, p.os.version, browser.name),
        );
    }
    let known_version = browser
        .versions
        .iter()
        .find(|v| v.full == p.browser.version)
        .cloned()
        .or_else(|| {
            pin.filter(|pin| **pin == p.browser.version)
                .map(|pin| VersionDef::pinned(pin))
        });
    c.warn_if(known_version.is_none(), "browser.known_version", || {
        format!("version `{}` is not in the dataset", p.browser.version)
    });
    let version = known_version.clone().unwrap_or_else(|| VersionDef {
        major: p.browser.major,
        ..VersionDef::pinned(&p.browser.version)
    });

    if let Some(os_version) = os_version {
        let ctx = UaContext {
            version: &version,
            kind,
            os_version,
            hw_model: device
                .and_then(|d| d.hw_model.as_deref())
                .unwrap_or_default(),
            locale: &p.locale,
            screen: (p.screen.width, p.screen.height, p.screen.device_pixel_ratio),
        };
        let expected_ua = ctx.render(template);
        c.fix_if(
            Severity::Error,
            nav.user_agent != expected_ua,
            "ua.matches_template",
            || json!(expected_ua),
            || format!("expected `{expected_ua}`"),
        );
        let expected_app = app_version(engine, os, &ctx, &nav.user_agent);
        c.fix_if(
            Severity::Error,
            nav.app_version != expected_app,
            "navigator.app_version",
            || json!(expected_app),
            || format!("expected `{expected_app}`"),
        );
        let expected_oscpu = oscpu(engine, os, &ctx);
        c.fix_if(
            Severity::Error,
            nav.oscpu != expected_oscpu,
            "navigator.oscpu",
            || json!(expected_oscpu),
            || format!("expected {expected_oscpu:?}"),
        );
    }
    let expected_platform = platform(engine, os);
    c.fix_if(
        Severity::Error,
        nav.platform != expected_platform,
        "navigator.platform",
        || json!(expected_platform),
        || format!("expected `{expected_platform}`"),
    );
    if let Some(max) = browser.max_cores {
        c.fix_if(
            Severity::Error,
            nav.hardware_concurrency > max,
            "navigator.hardware_concurrency_cap",
            || json!(max),
            || format!("`{}` caps cores at {max}", p.browser.id),
        );
    }

    match (&nav.user_agent_data, browser.client_hints) {
        (Some(_), false) => c.push_fix(
            Severity::Error,
            "uach.presence",
            format!("`{}` does not expose navigator.userAgentData", p.browser.id),
            Value::Null,
        ),
        (None, true) => c.push(
            Severity::Error,
            "uach.presence",
            format!("`{}` exposes navigator.userAgentData", p.browser.id),
        ),
        (Some(u), true) => {
            let brand = browser.ch_brand.as_deref().unwrap_or_default();
            let chromium = version.chromium_major();
            let brands = brand_list(
                chromium,
                brand,
                &version.major.to_string(),
                &chromium.to_string(),
                false,
            );
            c.fix_if(
                Severity::Error,
                u.brands != brands,
                "uach.brands",
                || json!(brands),
                || "brands do not match the GREASE list for this version".into(),
            );
            let full = brand_list(
                chromium,
                brand,
                &version.full,
                version.chromium_full(),
                true,
            );
            c.fix_if(
                Severity::Error,
                known_version.is_some() && u.full_version_list != full,
                "uach.full_version_list",
                || json!(full),
                || "fullVersionList does not match the version".into(),
            );
            c.fix_if(
                Severity::Error,
                u.mobile != (kind == Kind::Phone),
                "uach.mobile",
                || json!(kind == Kind::Phone),
                || "mobile must be true only on phones".into(),
            );
            let ch_platform = os.ch_platform.clone().unwrap_or_default();
            c.fix_if(
                Severity::Error,
                u.platform != ch_platform,
                "uach.platform",
                || json!(ch_platform),
                || format!("expected `{ch_platform}`"),
            );
            let architecture = device
                .and_then(|d| d.architecture.as_deref())
                .unwrap_or(&os.architecture);
            c.fix_if(
                Severity::Error,
                u.architecture != architecture || u.bitness != os.bitness,
                "uach.architecture",
                || json!({ "architecture": architecture, "bitness": os.bitness }),
                || format!("expected `{architecture}`/`{}`", os.bitness),
            );
            if let Some(v) = os_version {
                c.fix_if(
                    Severity::Error,
                    u.platform_version != v.platform_version,
                    "uach.platform_version",
                    || json!(v.platform_version),
                    || format!("expected `{}`", v.platform_version),
                );
            }
            if let Some(d) = device {
                let model = d.model.as_deref().unwrap_or_default();
                c.fix_if(
                    Severity::Error,
                    u.model != model,
                    "uach.model",
                    || json!(model),
                    || format!("expected `{model}`"),
                );
            }
        }
        (None, false) => {}
    }

    if let Some(renderer) = &p.webgl.unmasked_renderer {
        let known = data.devices.iter().any(|d| {
            d.os == p.os.id
                && d.webgl
                    .get(&engine)
                    .is_some_and(|g| &g.renderer == renderer)
        });
        c.warn_if(!known, "webgl.known_renderer", || {
            format!(
                "`{renderer}` is not known for {:?} on `{}`",
                engine, p.os.id
            )
        });
    }

    let mut allowed: BTreeSet<&str> = os.fonts.iter().map(String::as_str).collect();
    let base = allowed.clone();
    allowed.extend(
        os.versions
            .iter()
            .flat_map(|v| v.extra_fonts.iter().map(String::as_str)),
    );
    allowed.extend(
        crate::extras::fonts_locale::fonts_for(&p.os.id, &p.locale)
            .iter()
            .map(String::as_str),
    );
    let have: BTreeSet<&str> = p.fonts.iter().map(String::as_str).collect();
    let missing: Vec<_> = base.difference(&have).collect();
    c.warn_if(!missing.is_empty(), "fonts.os_base", || {
        format!("missing {} base fonts of `{}`", missing.len(), p.os.id)
    });
    let foreign: Vec<_> = have.difference(&allowed).collect();
    c.warn_if(!foreign.is_empty(), "fonts.foreign", || {
        format!("fonts not found on `{}`: {foreign:?}", p.os.id)
    });

    crate::validator::plausibility::check(data, p, device, browser, c);

    match data.locales.iter().find(|l| l.locale == p.locale) {
        None => {
            c.push(
                Severity::Warning,
                "locale.known",
                format!("locale `{}` is not in the dataset", p.locale),
            );
            crate::validator::plausibility::timezone_region(data, p, c);
        }
        Some(l) => {
            c.warn_if(
                !l.timezones.iter().any(|(t, _)| *t == p.timezone),
                "locale.timezone_plausible",
                || format!("`{}` is unusual for `{}`", p.timezone, p.locale),
            );
            let expected = languages_for(engine, &l.languages);
            c.fix_if(
                Severity::Warning,
                nav.languages != expected,
                "navigator.languages_typical",
                || json!(expected),
                || format!("expected {expected:?}"),
            );
        }
    }
}

/// Rules that hold for any browser, with or without the dataset.
fn generic_rules(p: &Profile, c: &mut Collector) {
    let nav = &p.navigator;
    let engine = p.browser.engine;
    let kind = p.device.kind;
    let s = &p.screen;

    c.fix_if(
        Severity::Error,
        nav.vendor != vendor(engine),
        "navigator.vendor",
        || json!(vendor(engine)),
        || format!("{engine:?} reports `{}`", vendor(engine)),
    );
    match (engine, nav.device_memory) {
        (Engine::Chromium, Some(m)) => c.error_if(
            !device_memory_values(p).contains(&m),
            "navigator.device_memory",
            || format!("{m} is not a value Chromium reports"),
        ),
        (Engine::Chromium, None) => c.push(
            Severity::Error,
            "navigator.device_memory",
            "Chromium always exposes deviceMemory".into(),
        ),
        (_, Some(_)) => c.push_fix(
            Severity::Error,
            "navigator.device_memory",
            "deviceMemory exists only in Chromium".into(),
            Value::Null,
        ),
        (_, None) => {}
    }
    c.error_if(
        !(1..=256).contains(&nav.hardware_concurrency),
        "navigator.hardware_concurrency",
        || "must be between 1 and 256".into(),
    );
    c.error_if(
        kind.is_handheld() && nav.max_touch_points == 0,
        "navigator.touch",
        || "phones and tablets report touch points".into(),
    );
    c.fix_if(
        Severity::Error,
        nav.languages.first() != Some(&nav.language),
        "navigator.languages",
        || json!(nav.languages.first()),
        || "languages[0] must equal language".into(),
    );
    c.fix_if(
        Severity::Warning,
        nav.language != p.locale,
        "navigator.language_locale",
        || json!(nav.language),
        || {
            format!(
                "language `{}` differs from locale `{}`",
                nav.language, p.locale
            )
        },
    );

    c.error_if(
        s.avail_width > s.width || s.avail_height > s.height,
        "screen.avail_within_screen",
        || "avail size exceeds screen size".into(),
    );
    c.error_if(
        p.viewport.width > s.avail_width || p.viewport.height > s.avail_height,
        "screen.viewport_within_avail",
        || "viewport exceeds available screen".into(),
    );
    c.error_if(
        !(0.5..=5.0).contains(&s.device_pixel_ratio),
        "screen.device_pixel_ratio",
        || "devicePixelRatio out of range".into(),
    );
    c.fix_if(
        Severity::Error,
        s.color_depth != s.pixel_depth,
        "screen.pixel_depth",
        || json!(s.color_depth),
        || "pixelDepth must equal colorDepth".into(),
    );
    c.warn_if(
        ![24, 30, 32].contains(&s.color_depth),
        "screen.color_depth",
        || format!("colorDepth {} is unusual", s.color_depth),
    );
    c.warn_if(
        kind == Kind::Phone && s.width > 600,
        "screen.phone_width",
        || "phone screens are narrower than 600 CSS px".into(),
    );
    c.warn_if(
        kind == Kind::Phone && s.width > s.height,
        "screen.phone_portrait",
        || "phone profiles describe the portrait orientation".into(),
    );
    c.warn_if(
        matches!(kind, Kind::Desktop | Kind::Laptop) && s.width < 1024,
        "screen.desktop_width",
        || "desktop screens are at least 1024 CSS px wide".into(),
    );

    let (mv, mr) = masked_webgl(engine);
    c.fix_if(
        Severity::Error,
        p.webgl.vendor != mv || p.webgl.renderer != mr,
        "webgl.masked",
        || json!({ "vendor": mv, "renderer": mr }),
        || format!("{engine:?} reports `{mv}` / `{mr}`"),
    );
    c.error_if(
        p.webgl.unmasked_vendor.is_some() != p.webgl.unmasked_renderer.is_some(),
        "webgl.unmasked_pair",
        || "unmasked vendor and renderer come together".into(),
    );
}

/// Chromium major of a Chromium-engine profile: the `Chromium` client-hint brand, else the browser major.
pub(crate) fn chromium_major(p: &Profile) -> u32 {
    p.navigator
        .user_agent_data
        .as_ref()
        .and_then(|u| u.brands.iter().find(|b| b.brand == "Chromium"))
        .and_then(|b| b.version.parse().ok())
        .unwrap_or(p.browser.major)
}

/// Values `navigator.deviceMemory` can take. Chromium 147 changed the buckets to 2-8 on Android and
/// 2-32 elsewhere (chromestatus feature 6330376953921536); both sets stay accepted from 147 on so
/// profiles built with the older buckets are not rejected.
pub(crate) fn device_memory_values(p: &Profile) -> Vec<f64> {
    let mut v = vec![0.25, 0.5, 1.0, 2.0, 4.0, 8.0];
    if chromium_major(p) >= 147 && p.os.id != "android" {
        v.extend([16.0, 32.0]);
    }
    v
}
